function generateCSS(): string {
  const lines: string[] = [];
  lines.push(HEADER_CSS);
  lines.push(':root {');

  // ---- Colors: primary, secondary, success, warning, error, info ----
  const colorGroups = ['primary', 'secondary', 'success', 'warning', 'error', 'info'] as const;
  for (const group of colorGroups) {
    const c = tokens.colors[group];
    const label = group.charAt(0).toUpperCase() + group.slice(1);
    lines.push(`  /* ===== ${label} ===== */`);

    // Semantic aliases
    lines.push(`  --color-${group}: ${c.main};`);
    lines.push(`  --color-${group}-hover: ${c.dark};`);
    lines.push(`  --color-${group}-light: ${c.light};`);
    if (c.contrastText) {
      lines.push(`  --color-${group}-foreground: ${c.contrastText};`);
    }

    // Full scale (50-900)
    for (let step = 50; step <= 900; step += 50) {
      const val = c[String(step)];
      if (val) {
        lines.push(`  --color-${group}-${step}: ${val};`);
      }
    }
    lines.push('');
  }

  // ---- Grey (scale only) ----
  {
    const c = tokens.colors.grey;
    lines.push(`  /* ===== Grey ===== */`);
    for (const key of Object.keys(c) as string[]) {
      lines.push(`  --color-grey-${key}: ${c[key]};`);
    }
    lines.push('');
  }

  // ---- Background & Surface ----
  {
    lines.push(`  /* ===== Background & Surface ===== */`);
    const bg = tokens.colors.background;
    lines.push(`  --color-background: ${bg.default};`);
    lines.push(`  --color-surface: ${bg.paper};`);
    // Derived surface tokens matching existing index.css
    lines.push(`  --color-surface-light: #f1f5f9;`);
    lines.push(`  --color-surface-hover: #e2e8f0;`);
    lines.push(`  --color-card: ${bg.paper};`);
    lines.push(`  --color-card-hover: #f1f5f9;`);
    lines.push('');
  }

  // ---- Text ----
  {
    lines.push(`  /* ===== Text ===== */`);
    const t = tokens.colors.text;
    lines.push(`  --color-text-primary: ${t.primary};`);
    lines.push(`  --color-text-secondary: ${t.secondary};`);
    lines.push(`  --color-text-muted: ${t.muted};`);
    lines.push(`  --color-text-disabled: ${t.disabled};`);
    lines.push('');
  }

  // ---- Border & Input ----
  {
    lines.push(`  /* ===== Border & Input ===== */`);
    const b = tokens.colors.border;
    lines.push(`  --color-border: ${b.default};`);
    lines.push(`  --color-border-light: ${b.light};`);
    lines.push(`  --color-input: ${b.default};`);
    lines.push(`  --color-ring: ${tokens.colors.primary.main};`);
    lines.push('');
  }

  // ---- Border Radius ----
  {
    lines.push(`  /* ===== Radius ===== */`);
    const r = tokens.borderRadius;
    for (const key of Object.keys(r) as string[]) {
      lines.push(`  --radius-${key}: ${r[key]}${typeof r[key] === 'number' ? 'px' : ''};`);
    }
    lines.push('');
  }

  // ---- Shadows (light mode) ----
  {
    lines.push(`  /* ===== Shadow (light) ===== */`);
    const s = tokens.shadows;
    for (const key of Object.keys(s) as string[]) {
      lines.push(`  --shadow-${key}: ${s[key]};`);
    }
    lines.push('');
  }

  // ---- Typography ----
  {
    lines.push(`  /* ===== Typography ===== */`);
    const typo = tokens.typography;
    lines.push(`  --font-sans: ${typo.fontFamily};`);
    lines.push(`  --font-mono: 'SF Mono', Monaco, 'Inconsolata', 'Fira Mono', 'Roboto Mono', monospace;`);
    lines.push('');

    for (const key of Object.keys(typo.fontSize) as string[]) {
      lines.push(`  --font-size-${key}: ${typo.fontSize[key]};`);
    }
    lines.push('');

    for (const key of Object.keys(typo.fontWeight) as string[]) {
      lines.push(`  --font-weight-${key}: ${typo.fontWeight[key]};`);
    }
    lines.push('');

    for (const key of Object.keys(typo.lineHeight) as string[]) {
      lines.push(`  --line-height-${key}: ${typo.lineHeight[key]};`);
    }
    lines.push('');
  }

  // ---- Spacing ----
  {
    lines.push(`  /* ===== Spacing ===== */`);
    const sp = tokens.spacing;
    for (const key of Object.keys(sp) as string[]) {
      const px = sp[key] as number;
      // Convert px to rem (base 16px): 4px => 0.25rem, 8px => 0.5rem, etc.
      const rem = px === 0 ? '0' : `${(px / 16).toFixed(px % 16 === 0 ? 0 : 2).replace(/\.?0+$/, '')}rem`;
      lines.push(`  --spacing-${key}: ${rem};`);
    }
    lines.push('');
  }

  // ---- Transitions / Motion ----
  {
    lines.push(`  /* ===== Transitions ===== */`);
    const motion = tokens.motion;
    for (const key of Object.keys(motion.duration) as string[]) {
      const val = motion.duration[key] as string;
      const ms = val.replace('ms', '');
      const mapKey: Record<string, string> = {
        instant: 'instant',
        fast: 'fast',
        normal: 'normal',
        slow: 'slow',
        deliberate: 'deliberate',
        skeleton: 'skeleton',
      };
      const label = mapKey[key] || key;
      lines.push(`  --transition-${label}: ${val} ${motion.easing.default};`);
    }
    lines.push('');
  }

  // ---- Gradients ----
  {
    lines.push(`  /* ===== Module Gradient Accents ===== */`);
    lines.push(`  --gradient-primary: ${gradients.primary};`);
    lines.push(`  --gradient-secondary: ${gradients.secondary};`);
    lines.push(`  --gradient-brand: ${gradients.brand};`);
    lines.push(`  --gradient-text: ${gradients.text};`);
    for (const key of Object.keys(gradients.modules) as string[]) {
      lines.push(`  --gradient-module-${key}: ${gradients.modules[key]};`);
    }
    lines.push('');
  }

  lines.push('}');

  // ---- Dark mode overrides ----
  lines.push('');
  lines.push('/* ===== Dark Mode ===== */');
  lines.push('.dark {');

  // Dark color overrides
  lines.push(`  --color-primary: ${tokens.colors.primary[400]};`);
  lines.push(`  --color-primary-hover: ${tokens.colors.primary[500]};`);
  lines.push(`  --color-primary-foreground: #0f172a;`);

  lines.push(`  --color-secondary: ${tokens.colors.secondary[400]};`);
  lines.push(`  --color-secondary-hover: ${tokens.colors.secondary[500]};`);
  lines.push(`  --color-secondary-foreground: #0f172a;`);

  lines.push(`  --color-success: ${tokens.colors.success[400]};`);
  lines.push(`  --color-success-hover: ${tokens.colors.success[500]};`);
  lines.push(`  --color-success-foreground: #0f172a;`);

  lines.push(`  --color-warning: ${tokens.colors.warning[400]};`);
  lines.push(`  --color-warning-hover: ${tokens.colors.warning[500]};`);
  lines.push(`  --color-warning-foreground: #0f172a;`);

  lines.push(`  --color-error: ${tokens.colors.error[400]};`);
  lines.push(`  --color-error-hover: ${tokens.colors.error[500]};`);
  lines.push(`  --color-error-foreground: #ffffff;`);

  lines.push(`  --color-info: ${tokens.colors.info[400]};`);
  lines.push(`  --color-info-hover: ${tokens.colors.info[500]};`);
  lines.push(`  --color-info-foreground: #0f172a;`);

  // Dark backgrounds
  lines.push(`  --color-background: #0f172a;`);
  lines.push(`  --color-surface: #1e293b;`);
  lines.push(`  --color-surface-light: #334155;`);
  lines.push(`  --color-surface-hover: #475569;`);
  lines.push(`  --color-card: #1e293b;`);
  lines.push(`  --color-card-hover: #334155;`);

  // Dark text
  lines.push(`  --color-text-primary: #f8fafc;`);
  lines.push(`  --color-text-secondary: #94a3b8;`);
  lines.push(`  --color-text-muted: #64748b;`);
  lines.push(`  --color-text-disabled: #64748b;`);

  // Dark borders
  lines.push(`  --color-border: #334155;`);
  lines.push(`  --color-border-light: #475569;`);
  lines.push(`  --color-input: #334155;`);
  lines.push(`  --color-ring: ${tokens.colors.primary[400]};`);

  // Dark shadows
  const ds = tokens.darkShadows;
  for (const key of Object.keys(ds) as string[]) {
    lines.push(`  --shadow-${key}: ${ds[key]};`);
  }

  lines.push('}');

  return lines.join('\n') + '\n';
}

