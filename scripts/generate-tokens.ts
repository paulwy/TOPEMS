// ---------------------------------------------------------------------------
// 1. Parse tokens.ts  –  extract the `designTokens` object literal
// ---------------------------------------------------------------------------

function extractObjectLiteral(source: string, exportName: string): string {
  // Match `export const <name> = { ... };` (greedy brace matching)
  const pattern = new RegExp(
    `export\\s+const\\s+${exportName}\\s*=\\s*`,
  );
  const idx = source.search(pattern);
  if (idx === -1) throw new Error(`Cannot find export "${exportName}" in source`);

  const afterEquals = source.slice(idx + source.slice(idx).search('=') + 1);
  // Skip whitespace after '='
  let pos = 0;
  while (pos < afterEquals.length && /\s/.test(afterEquals[pos])) pos++;

  // Now we should be at '{'. Match braces.
  let depth = 0;
  let end = pos;
  for (let i = pos; i < afterEquals.length; i++) {
    if (afterEquals[i] === '{') depth++;
    else if (afterEquals[i] === '}') {
      depth--;
      if (depth === 0) { end = i + 1; break; }
    }
  }

  return afterEquals.slice(pos, end);
}

function evalTokens(objStr: string): any {
  // Strip TypeScript annotations: comments, `as const`, trailing commas are ok in JS
  const cleaned = objStr
    .replace(/\/\/.*$/gm, '')          // remove single-line comments
    .replace(/\/\*[\s\S]*?\*\//g, '')  // remove multi-line comments
    .replace(/\bas\s+const\b/g, '')    // remove `as const`
    .replace(/,\s*([}\]])/g, '$1');    // remove trailing commas
  return new Function(`"use strict"; return (${cleaned})`)();
}

const tokensSource = fs.readFileSync(TOKENS_SRC, 'utf-8');
const tokensObjStr = extractObjectLiteral(tokensSource, 'designTokens');
const tokens = evalTokens(tokensObjStr) as any;

