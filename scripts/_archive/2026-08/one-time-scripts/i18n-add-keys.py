def add_keys(filepath, keys_dict, key_name):
    with open(filepath, 'r') as f:
        data = json.load(f)
    
    data[key_name] = keys_dict
    
    with open(filepath, 'w') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')
    
    print(f"Added {len(keys_dict)} keys [{key_name}] to {filepath}")

