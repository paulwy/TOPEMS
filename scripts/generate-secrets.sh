#!/bin/bash

# TOPEMS 生产环境密钥生成脚本
# 用于生成安全的生产环境配置

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${YELLOW}========================================${NC}"
echo -e "${YELLOW}TOPEMS 生产环境密钥生成器${NC}"
echo -e "${YELLOW}========================================${NC}"
echo ""

# 生成随机字符串函数
generate_secret() {
    local length=${1:-64}
    if command -v openssl &> /dev/null; then
        openssl rand -base64 $((length * 3 / 4)) | tr -d '\n' | tr -d '/+=' | head -c $length
    else
        # 如果没有 openssl，使用更简单的方法
        LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c $length
    fi
}

# 生成密钥
echo -e "${GREEN}正在生成密钥...${NC}"
JWT_SECRET=$(generate_secret 64)
JWT_REFRESH_SECRET=$(generate_secret 64)
SESSION_SECRET=$(generate_secret 64)
POSTGRES_PASSWORD=$(generate_secret 32)

echo ""
echo -e "${BLUE}生成的密钥：${NC}"
echo ""
echo -e "JWT_SECRET=${GREEN}${JWT_SECRET}${NC}"
echo -e "JWT_REFRESH_SECRET=${GREEN}${JWT_REFRESH_SECRET}${NC}"
echo -e "SESSION_SECRET=${GREEN}${SESSION_SECRET}${NC}"
echo -e "POSTGRES_PASSWORD=${GREEN}${POSTGRES_PASSWORD}${NC}"
echo ""

# 询问是否更新 .env.production
read -p "是否更新 .env.production 文件？(y/n): " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
    if [ -f ".env.production" ]; then
        cp ".env.production" ".env.production.backup.$(date +%Y%m%d%H%M%S)"
        echo -e "${YELLOW}已备份原文件为 .env.production.backup.*${NC}"
    fi
    
    cat > ".env.production" << EOF
# TOPEMS Production Environment Configuration
# Auto-generated by generate-secrets.sh on $(date)

POSTGRES_HOST=postgres
POSTGRES_PORT=5432
POSTGRES_USER=topems
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=topems

REDIS_HOST=redis
REDIS_PORT=6379
REDIS_PASSWORD=

RUST_LOG=info
RUST_BACKTRACE=0

BACKEND_PORT=8080
NOTIFICATION_PORT=8081
REPORT_PORT=8082
DOC_PORT=8083
FLOW_PORT=8084
IAM_PORT=8085
LIMS_PORT=8086
QMS_PORT=8087
RS_PORT=8088
EHS_PORT=8089
SRM_PORT=8090
AI_PORT=8091

DATABASE_URL=postgres://\${POSTGRES_USER}:\${POSTGRES_PASSWORD}@\${POSTGRES_HOST}:\${POSTGRES_PORT}/\${POSTGRES_DB}
REDIS_URL=redis://\${REDIS_HOST}:\${REDIS_PORT}

JWT_SECRET=${JWT_SECRET}
JWT_EXPIRATION=86400
JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET}
SESSION_SECRET=${SESSION_SECRET}

# 生产环境请设置为实际域名
FRONTEND_URL=https://your-domain.com
API_URL=https://api.your-domain.com

MAX_UPLOAD_SIZE=104857600
EOF
    
    echo -e "${GREEN}✓ .env.production 已更新${NC}"
    echo -e "${YELLOW}请记得更新 FRONTEND_URL 和 API_URL 为实际域名${NC}"
fi

# 询问是否更新前端配置
echo ""
read -p "是否同时创建前端生产环境配置示例？(y/n): " -n 1 -r
echo
if [[ $REPLY =~ ^[Yy]$ ]]; then
    cat > "frontend/.env.production.example" << 'EOF'
# TOPEMS Frontend Production Environment Configuration
# Copy this file to .env.production and modify accordingly

# API Base URL - 生产环境请使用实际域名
VITE_API_BASE_URL=https://api.your-domain.com
VITE_API_TIMEOUT=30000

# WebSocket URL
VITE_WS_URL=wss://api.your-domain.com

# Service URLs - 各微服务地址
VITE_IAM_SERVICE_URL=https://iam.your-domain.com
VITE_DOC_SERVICE_URL=https://doc.your-domain.com
VITE_AI_SERVICE_URL=https://ai.your-domain.com
VITE_FLOW_SERVICE_URL=https://flow.your-domain.com
VITE_EHS_SERVICE_URL=https://ehs.your-domain.com
VITE_LIMS_SERVICE_URL=https://lims.your-domain.com
VITE_PDM_SERVICE_URL=https://pdm.your-domain.com
VITE_QMS_SERVICE_URL=https://qms.your-domain.com
VITE_RS_SERVICE_URL=https://rs.your-domain.com
VITE_SRM_SERVICE_URL=https://srm.your-domain.com
VITE_ERP_SERVICE_URL=https://erp.your-domain.com
VITE_NOTIFICATION_SERVICE_URL=https://notification.your-domain.com
VITE_REPORT_SERVICE_URL=https://report.your-domain.com
VITE_GIS_SERVICE_URL=https://gis.your-domain.com
VITE_BI_SERVICE_URL=https://bi.your-domain.com
VITE_MOBILE_SERVICE_URL=https://mobile.your-domain.com
VITE_IM_SERVICE_URL=https://im.your-domain.com
VITE_INTEGRATION_SERVICE_URL=https://integration.your-domain.com
VITE_WMS_SERVICE_URL=https://wms.your-domain.com
VITE_HRM_SERVICE_URL=https://hrm.your-domain.com
VITE_CRM_SERVICE_URL=https://crm.your-domain.com
VITE_MES_SERVICE_URL=https://mes.your-domain.com

# Feature Flags
VITE_ENABLE_DEBUG_MODE=false
VITE_ENABLE_HOT_RELOAD=false
VITE_ENABLE_API_DOCS=false
VITE_ENABLE_MOCK_DATA=false

# File Upload
VITE_MAX_UPLOAD_SIZE=104857600
VITE_ALLOWED_FILE_TYPES=jpg,jpeg,png,gif,pdf,doc,docx,xls,xlsx,zip,rar,txt,md

# Theme
VITE_DEFAULT_THEME=light
VITE_ENABLE_DARK_MODE=true

# Logging
VITE_LOG_LEVEL=info
EOF
    echo -e "${GREEN}✓ frontend/.env.production.example 已创建${NC}"
fi

echo ""
echo -e "${YELLOW}========================================${NC}"
echo -e "${GREEN}密钥生成完成！${NC}"
echo ""
echo -e "${RED}⚠ 重要提示：${NC}"
echo -e "1. 请妥善保管生成的密钥，不要提交到版本控制系统"
echo -e "2. 确保 .env.production 文件被添加到 .gitignore"
echo -e "3. 在不同环境使用不同的密钥"
echo -e "4. 定期更换密钥"
echo -e "${YELLOW}========================================${NC}"
