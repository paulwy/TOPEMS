// Sort keys by length descending for greedy matching
const sortedKeys = Object.keys(T).sort((a, b) => b.length - a.length);

function translateSegment(text) {
  let result = text;
  for (const key of sortedKeys) {
    if (result.includes(key)) {
      result = result.split(key).join(T[key]);
    }
  }
  return result;
}

function translate(zh) {
  // Check for prefix pattern: lowercase.word
  const prefixMatch = zh.match(/^([a-z]+)\.(.*)$/s);
  if (prefixMatch) {
    const prefix = prefixMatch[1] + '.';
    const suffix = prefixMatch[2];
    return prefix + translateSegment(suffix);
  }
  return translateSegment(zh);
}

