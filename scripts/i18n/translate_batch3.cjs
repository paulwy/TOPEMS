// ---- Translation function ----
function translate(item) {
  const zh = item.zh;
  const path = item.path;

  // 1. Check multi-line overrides by path
  if (MULTILINE_OVERRIDES[path]) {
    return MULTILINE_OVERRIDES[path];
  }

  // 2. Check exact overrides
  if (OVERRIDES[zh] !== undefined) {
    return OVERRIDES[zh];
  }

  // 3. Handle EN: prefix
  let s = zh;
  if (s.startsWith('EN:')) {
    s = s.slice(3);
    // translate the rest using DICT and known patterns
    s = translateWithDict(s);
    return s;
  }

  // 4. If pure ASCII already, return as-is
  if (!/[\u4e00-\u9fff]/.test(s)) {
    return s;
  }

  // 5. Apply dictionary-based translation for residual mixed content
  return translateWithDict(s);
}

function translateWithDict(s) {
  // Apply longest-match-first dictionary replacements
  // First, handle multi-char phrases
  const keys = Object.keys(DICT).sort((a, b) => b.length - a.length);
  let result = s;
  for (const k of keys) {
    // Only replace Chinese keys
    if (!/[\u4e00-\u9fff]/.test(k)) continue;
    // Use split-join for global replacement
    result = result.split(k).join(DICT[k]);
  }
  // Clean up: capitalize first letter, fix spacing
  result = cleanupSpacing(result);
  return result;
}

function cleanupSpacing(s) {
  // Fix double spaces
  s = s.replace(/ {2,}/g, ' ');
  // Fix space before punctuation
  s = s.replace(/\s+([,.;:!?])/g, '$1');
  // Fix space after Chinese punctuation that remains
  s = s.replace(/([，。；：！？、])/g, function (m) {
    const map = { '，': ',', '。': '.', '；': ';', '：': ':', '！': '!', '？': '?', '、': ',' };
    return map[m] || m;
  });
  // Capitalize first letter if lowercase at start
  s = s.replace(/^([a-z])/, function (m) {
    return m.toUpperCase();
  });
  return s.trim();
}

