// TOPEMS 服务配置 - 与各微服务实际数据库表结构对齐

export interface FieldConfig {
    name: string;
    type: string;
    primaryKey?: boolean;
    notNull?: boolean;
    default?: string;
    unique?: boolean;
    index?: boolean;
    searchable?: boolean;
    references?: string;
    comment?: string;
}

export interface ForeignKeyConfig {
    column: string;
    references: string;
    onDelete?: 'RESTRICT' | 'CASCADE' | 'SET NULL' | 'NO ACTION';
    onUpdate?: 'CASCADE' | 'RESTRICT' | 'NO ACTION';
    constraintName?: string;
}

export interface CompositeIndexConfig {
    name?: string;
    columns: string[];
    unique?: boolean;
}

export interface TableConfig {
    name: string;
    description: string;
    fields: FieldConfig[];
    foreignKeys?: ForeignKeyConfig[];
    compositeIndexes?: CompositeIndexConfig[];
}

export interface ServiceConfig {
    name: string;
    display_name: string;
    description: string;
    schema: string;
    port: number;
    tables: TableConfig[];
}

