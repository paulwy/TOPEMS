function translateValue(zhVal) {
  // 1. Direct dictionary hit
  if (D[zhVal]) return D[zhVal];

  // 2. For values with placeholders, translate Chinese parts
  if (/\$\{.*?\}|\{\{.*?\}\}/.test(zhVal) || /[\u4e00-\u9fff]/.test(zhVal)) {
    let result = zhVal;
    // Try full-phrase dictionary first (longest match)
    const dKeys = Object.keys(D).filter(k => /[\u4e00-\u9fff]/.test(k)).sort((a, b) => b.length - a.length);
    for (const k of dKeys) {
      while (result.includes(k)) {
        result = result.replace(k, D[k]);
      }
    }
    // Then try word-level dictionary for remaining Chinese
    const wKeys = Object.keys(W).filter(k => /[\u4e00-\u9fff]/.test(k)).sort((a, b) => b.length - a.length);
    for (const k of wKeys) {
      while (result.includes(k)) {
        result = result.replace(k, W[k]);
      }
    }
    if (result !== zhVal && !/[\u4e00-\u9fff]/.test(result)) {
      return result;
    }
    // If there's still Chinese, return the partially translated result
    // (it's still better than the original mixed state)
    if (result !== zhVal) {
      return result;
    }
  }

  return null;
}

let totalFixed = 0;
let totalRemaining = 0;
const stillChinese = new Set();

// ====== 实际入口 ======
const OPTS = parseArgs(process.argv.slice(2));
if (OPTS.help) { process.stdout.write(USAGE); process.exit(0); }
const dir = DEFAULT_DIR;
const files = OPTS.ns && OPTS.ns.length ? OPTS.ns.filter((n) => DEFAULT_FILES.includes(n)) : DEFAULT_FILES;
process.stderr.write(
  `[fix-residual-chinese] ${OPTS.apply ? 'APPLY 写磁盘' : 'DRY-RUN（加 --apply 才写）'}\n` +
  `[fix-residual-chinese] 命名空间: ${files.join(', ')}\n\n`
);

for (const f of files) {
  const zhPath = path.resolve(dir + 'zh/' + f + '.json');
  const enPath = path.resolve(dir + 'en/' + f + '.json');
  const zh = JSON.parse(fs.readFileSync(zhPath, 'utf8'));
  const en = JSON.parse(fs.readFileSync(enPath, 'utf8'));

  let fixed = 0;
  let remaining = 0;

  function fix(zhObj, enObj) {
    for (const k of Object.keys(zhObj)) {
      if (typeof zhObj[k] === 'object' && zhObj[k] !== null) {
        if (!enObj[k] || typeof enObj[k] !== 'object') enObj[k] = {};
        fix(zhObj[k], enObj[k]);
      } else {
        const enVal = enObj[k];
        if (typeof enVal === 'string' && /[\u4e00-\u9fff]/.test(enVal)) {
          const zhVal = zhObj[k];
          const translated = translateValue(zhVal);
          if (translated !== null && translated !== zhVal) {
            enObj[k] = translated;
            fixed++;
            if (/[\u4e00-\u9fff]/.test(translated)) {
              stillChinese.add(zhVal);
              remaining++;
            }
          } else {
            stillChinese.add(zhVal);
            remaining++;
          }
        }
      }
    }
  }

  fix(zh, en);
  if (OPTS.apply) {
    fs.writeFileSync(enPath, JSON.stringify(en, null, 2) + '\n', 'utf8');
  }
  const action = OPTS.apply ? 'fixed' : 'would fix';
  console.log(`${f}.json: ${action} ${fixed}, still Chinese: ${remaining}`);
  totalFixed += fixed;
  totalRemaining += remaining;
}

const actionTotal = OPTS.apply ? 'Total fixed' : 'Total would fix';
console.log(`\n${actionTotal}: ${totalFixed}`);
console.log('Total still with Chinese: ' + totalRemaining);
if (stillChinese.size > 0 && stillChinese.size <= 50) {
  console.log('\nUntranslated values:');
  for (const v of stillChinese) {
    console.log('  ' + JSON.stringify(v));
  }
}
if (!OPTS.apply && totalFixed > 0) {
  process.stderr.write(
    `\n[fix-residual-chinese] 💡 当前为 DRY-RUN，加 --apply 才会写 en/*.json 文件。\n`
  );
}
