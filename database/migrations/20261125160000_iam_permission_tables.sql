-- 2026-11-26 · iam 权限表（DatabasePermissionStore 的后端存储）
--
-- 背景：svc/unified-core/src/routes/business_tools/database_permission_store.rs 一直在用
--
--   INSERT INTO iam.tenant_permissions (tenant_id, user_id, role, active) ... RETURNING id
--   INSERT INTO iam.tool_permissions (tenant_permission_id, tool_name, max_permission,
--                                     allowed_operations, denied_operations)
--   SELECT id, tenant_id, user_id, role, active, created_at, updated_at ... deleted_at IS NULL
--
-- 但这两张表在 anchor/prod 血缘里根本不存在，且历史迁移（20260825000000 / 20260827000000 /
-- 20261007000012 已在账本里）从未真正落地。代码头部原记录："id bigint NOT NULL 没有默认值
-- 或 identity，本实现的 INSERT 不提供 id，因此启用 database store 前需先补 id 生成"。
--
-- 决策：把表建出来并给 id 加 identity，让「数据库版权限存储」成为可选项而不是地雷。
--   * 默认仍然走 Memory 实现（PermissionStore::memory），本迁移不改变默认行为；
--   * 需要多实例共享权限时，切到 DatabasePermissionStore 即可用，无需再改 schema。
--
-- 类型依据代码：tenant_id / user_id / role / max_permission / tool_name 均为 TEXT，
-- active BOOLEAN，allowed_operations / denied_operations 为 Vec<String> → TEXT[]，
-- tenant_permission_id 为 BIGINT（RETURNING id 的 i64）。
-- 非破坏：CREATE TABLE IF NOT EXISTS + IF NOT EXISTS 列/索引。

CREATE TABLE IF NOT EXISTS iam.tenant_permissions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   text NOT NULL,
    user_id     text NOT NULL,
    role        text NOT NULL,
    active      boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    deleted_at  timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_iam_tenant_permissions_tenant_user
    ON iam.tenant_permissions (tenant_id, user_id);

CREATE TABLE IF NOT EXISTS iam.tool_permissions (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_permission_id  bigint NOT NULL
                          REFERENCES iam.tenant_permissions (id) ON DELETE CASCADE,
    tool_name             text NOT NULL,
    max_permission        text NOT NULL,
    allowed_operations    text[] NOT NULL DEFAULT '{}',
    denied_operations     text[] NOT NULL DEFAULT '{}',
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_iam_tool_permissions_tenant_tool
    ON iam.tool_permissions (tenant_permission_id, tool_name);

-- 存量血缘（anchor/prod 的 pg_dump 基线）里这两张表**已经存在**，且 `id bigint NOT NULL`
-- 没有 identity / 默认值 —— 正是 V448 记的那个缺陷。CREATE IF NOT EXISTS 对它们是 no-op，
-- 所以这里必须把 id 生成补上：只有「既无 identity 也无默认值」时才加 GENERATED BY DEFAULT，
-- 加完再用 setval 把序列推到 max(id)+1，避免和已有行的显式 id 撞号。
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = 'iam.tenant_permissions'::regclass
          AND attname = 'id'
          AND (attidentity <> '' OR atthasdef)
    ) THEN
        ALTER TABLE iam.tenant_permissions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(pg_get_serial_sequence('iam.tenant_permissions', 'id'),
                       GREATEST(COALESCE((SELECT max(id) FROM iam.tenant_permissions), 0), 1));
        RAISE NOTICE 'iam.tenant_permissions.id 补装 identity';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = 'iam.tool_permissions'::regclass
          AND attname = 'id'
          AND (attidentity <> '' OR atthasdef)
    ) THEN
        ALTER TABLE iam.tool_permissions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(pg_get_serial_sequence('iam.tool_permissions', 'id'),
                       GREATEST(COALESCE((SELECT max(id) FROM iam.tool_permissions), 0), 1));
        RAISE NOTICE 'iam.tool_permissions.id 补装 identity';
    END IF;
END $$;

-- 存量血缘的 allowed_operations / denied_operations 是可空的 text[]，代码按 Option 读、
-- 写入恒有值，这里只补默认空数组，不动可空性（避免对已有 NULL 行做强约束）。
ALTER TABLE iam.tool_permissions ALTER COLUMN allowed_operations SET DEFAULT '{}';
ALTER TABLE iam.tool_permissions ALTER COLUMN denied_operations SET DEFAULT '{}';

-- 运行期角色需要读写（表由 topems_owner 建，DML 授权给 topems_app）
GRANT SELECT, INSERT, UPDATE, DELETE ON iam.tenant_permissions TO topems_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON iam.tool_permissions TO topems_app;
GRANT USAGE, SELECT ON SEQUENCE iam.tenant_permissions_id_seq TO topems_app;
GRANT USAGE, SELECT ON SEQUENCE iam.tool_permissions_id_seq TO topems_app;

-- 租户隔离：只对 tenant_permissions 启 RLS（tool_permissions 通过外键挂在父表下，跟随父行的可见性）。
-- tenant_id 在代码里是 TEXT；GUC 里是 uuid 文本，直接按文本比较即可：
-- 未设置 / 空 / 零租户 → 全放行（平台维护态）；否则按租户过滤。
ALTER TABLE iam.tenant_permissions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation_tenant_permissions ON iam.tenant_permissions;
CREATE POLICY tenant_isolation_tenant_permissions ON iam.tenant_permissions
    USING (
        NULLIF(current_setting('app.tenant_id', true), '') IS NULL
        OR NULLIF(current_setting('app.tenant_id', true), '') = ''
        OR NULLIF(current_setting('app.tenant_id', true), '') = '00000000-0000-0000-0000-000000000000'
        OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')
    );
