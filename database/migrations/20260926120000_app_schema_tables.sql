-- 背景：ehs/lims 的建表逻辑在 Rust 代码 init_database() 内，迁移链未覆盖；
--       集成测试直连 DB 时表缺失/骨架导致失败。本迁移把表结构固化进迁移链，
--       全新环境执行 db_migrate / sqlx migrate run 即可一键建全（幂等）。
-- 2026-09-26

