export function getStatusLabel(statusCode: string, statusMap: Record<string, StatusConfig>): string {
  return statusMap[statusCode]?.label || statusCode;
}

export function getStatusColor(statusCode: string, statusMap: Record<string, StatusConfig>): StatusConfig['color'] {
  return statusMap[statusCode]?.color || 'info';
}

export function getStatusConfig(statusCode: string, statusMap: Record<string, StatusConfig>): StatusConfig | undefined {
  return statusMap[statusCode];
}

export function getAllStatusOptions(statusMap: Record<string, StatusConfig>): { value: string; label: string }[] {
  return Object.values(statusMap)
    .sort((a, b) => a.order - b.order)
    .map((config) => ({ value: config.code, label: config.label }));
}