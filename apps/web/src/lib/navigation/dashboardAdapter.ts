const defaultColor = 'bg-blue-500';

export function convertModuleCardToModuleItem(moduleCard: ModuleCardConfig): ModuleItem {
  const Icon = iconMap[moduleCard.icon] || defaultIcon;

  return {
    title: moduleCard.name,
    icon: Icon as any,
    description: moduleCard.description || i18n.t('shared.dashboard_adapter.k0'),
    path: moduleCard.path,
    color: moduleColorMap[moduleCard.code] || defaultColor,
    status: moduleCard.status || 'online',
    permission: moduleCard.permission || null,
    module: moduleCard.code,
    adminOnly:
      moduleCard.permission?.includes('admin') || moduleCard.permission?.includes('system'),
  };
}

export function convertModuleCardsToModuleItems(moduleCards: ModuleCardConfig[]): ModuleItem[] {
  return moduleCards.map(convertModuleCardToModuleItem);
}
