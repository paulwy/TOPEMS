def set_nested(d, key_path, value):
    """Set a nested value in dict using dot-separated key path."""
    keys = key_path.split(".")
    for k in keys[:-1]:
        d = d[k]
    d[keys[-1]] = value


def fix_file(file_path, lang):
    """Fix placeholder values in a JSON file."""
    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    fixed_count = 0
    for key_path, (zh, en) in TRANSLATIONS.items():
        value = zh if lang == "zh" else en
        try:
            set_nested(data, key_path, value)
            fixed_count += 1
        except (KeyError, TypeError):
            pass

    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    return fixed_count


