def translate_value(zh_value):
    """Translate a Chinese value to English."""
    if not isinstance(zh_value, str):
        return zh_value

    # Direct lookup
    if zh_value in TRANSLATIONS:
        return TRANSLATIONS[zh_value]

    # Try with interpolation variables replaced
    # Handle patterns like "{{var}}" or "${var}"
    template = zh_value
    # Replace ${var} and {{var}} with placeholders for matching
    import re
    placeholder_pattern = re.compile(r'\$\{[^}]+\}|\{\{[^}]+\}\}')
    matches = placeholder_pattern.findall(zh_value)
    if matches:
        # Try matching with placeholder normalization
        normalized = placeholder_pattern.sub('{{var}}', zh_value)
        if normalized in TRANSLATIONS:
            return TRANSLATIONS[normalized]

    # If value contains Chinese, return it with a prefix for manual review
    if re.search(r'[\u4e00-\u9fff]', zh_value):
        return zh_value  # Return as-is, will be manually reviewed

    return zh_value


def translate_object(obj):
    """Recursively translate all values in a nested object."""
    if isinstance(obj, dict):
        return {k: translate_object(v) for k, v in obj.items()}
    elif isinstance(obj, list):
        return [translate_object(item) for item in obj]
    else:
        return translate_value(obj)


