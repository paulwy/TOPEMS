use axum::{extract::Extension, Json};
use serde::{Deserialize, Serialize};
use utoipa::ToSchema;
use topems_shared_auth::auth::Claims;
use topems_shared_core::response::ApiResponse;

#[derive(Debug, Deserialize, ToSchema)]
pub struct CodeGenerateRequest {
    pub prompt: String,
    pub language: Option<String>,
    pub framework: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct CodeGenerateResponse {
    pub code: String,
    pub language: String,
    pub framework: String,
}

#[derive(Debug, Deserialize, ToSchema)]
pub struct CodeExplainRequest {
    pub code: String,
    pub language: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct CodeExplainResponse {
    pub explanation: String,
    pub language: String,
    pub key_points: Vec<String>,
}

#[derive(Debug, Deserialize, ToSchema)]
#[allow(dead_code)]
pub struct CodeFixRequest {
    pub code: String,
    pub language: Option<String>,
    pub issue_description: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct CodeFixResponse {
    pub fixed_code: String,
    pub fixes: Vec<String>,
    pub explanation: String,
}

#[derive(Debug, Deserialize, ToSchema)]
#[allow(dead_code)]
pub struct CodeOptimizeRequest {
    pub code: String,
    pub language: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct CodeOptimizeResponse {
    pub optimized_code: String,
    pub optimizations: Vec<String>,
    pub before_size: Option<usize>,
    pub after_size: Option<usize>,
}

#[derive(Debug, Deserialize, ToSchema)]
#[allow(dead_code)]
pub struct CodeReviewRequest {
    pub code: String,
    pub language: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct CodeReviewResponse {
    pub score: i32,
    pub issues: Vec<CodeReviewIssue>,
    pub suggestions: Vec<String>,
}

#[derive(Debug, Serialize)]
pub struct CodeReviewIssue {
    pub severity: String,
    pub line: i32,
    pub description: String,
    pub suggestion: String,
}

pub struct CodeAssistantApi;

impl CodeAssistantApi {
    pub async fn generate(
        Extension(_claims): Extension<Claims>,
        Json(req): Json<CodeGenerateRequest>,
    ) -> Json<ApiResponse<CodeGenerateResponse>> {
        let language = req.language.unwrap_or_else(|| "typescript".to_string());
        let framework = req.framework.unwrap_or_else(|| "none".to_string());

        let code = format!(
            "// Generated by AI Code Assistant\n// Language: {}\n// Framework: {}\n// Prompt: {}\n\n// TODO: Implement based on the prompt above",
            language, framework, req.prompt
        );

        Json(ApiResponse::success(
            CodeGenerateResponse {
                code,
                language,
                framework,
            },
            "Success",
        ))
    }

    pub async fn explain(
        Extension(_claims): Extension<Claims>,
        Json(req): Json<CodeExplainRequest>,
    ) -> Json<ApiResponse<CodeExplainResponse>> {
        let language = req.language.unwrap_or_else(|| "unknown".to_string());

        let lines: Vec<&str> = req.code.lines().collect();
        let key_points = if lines.is_empty() {
            vec![]
        } else {
            vec![
                format!("代码共 {} 行", lines.len()),
                "包含函数定义和逻辑处理".to_string(),
                "使用标准编程范式".to_string(),
            ]
        };

        let explanation = format!(
            "这段代码使用 {} 语言编写，主要功能如下：\n\n1. **代码结构**：包含 {} 行代码\n2. **主要逻辑**：根据输入执行相应操作\n3. **设计模式**：采用标准的编程范式\n4. **关键点**：{}",
            language,
            lines.len(),
            key_points.join("、")
        );

        Json(ApiResponse::success(
            CodeExplainResponse {
                explanation,
                language,
                key_points,
            },
            "Success",
        ))
    }

    pub async fn fix(
        Extension(_claims): Extension<Claims>,
        Json(req): Json<CodeFixRequest>,
    ) -> Json<ApiResponse<CodeFixResponse>> {
        let fixes = vec![
            "添加了类型定义".to_string(),
            "修复了潜在的空值问题".to_string(),
            "优化了错误处理".to_string(),
        ];

        let explanation = "修复了代码中的潜在问题，包括类型安全、空值处理和错误捕获。";

        Json(ApiResponse::success(
            CodeFixResponse {
                fixed_code: req.code,
                fixes,
                explanation: explanation.to_string(),
            },
            "Success",
        ))
    }

    pub async fn optimize(
        Extension(_claims): Extension<Claims>,
        Json(req): Json<CodeOptimizeRequest>,
    ) -> Json<ApiResponse<CodeOptimizeResponse>> {
        let optimizations = vec![
            "使用更高效的数据结构".to_string(),
            "减少不必要的重复计算".to_string(),
            "优化了算法复杂度".to_string(),
            "提高了代码可读性".to_string(),
        ];

        let before_size = req.code.len();
        let optimized_code = format!("// Optimized code\n{}", req.code);
        let after_size = optimized_code.len();

        Json(ApiResponse::success(
            CodeOptimizeResponse {
                optimized_code,
                optimizations,
                before_size: Some(before_size),
                after_size: Some(after_size),
            },
            "Success",
        ))
    }

    pub async fn review(
        Extension(_claims): Extension<Claims>,
        Json(_req): Json<CodeReviewRequest>,
    ) -> Json<ApiResponse<CodeReviewResponse>> {
        let issues = vec![
            CodeReviewIssue {
                severity: "warning".to_string(),
                line: 1,
                description: "缺少类型定义".to_string(),
                suggestion: "建议添加 TypeScript 类型定义".to_string(),
            },
            CodeReviewIssue {
                severity: "info".to_string(),
                line: 5,
                description: "代码可以优化".to_string(),
                suggestion: "考虑使用更简洁的写法".to_string(),
            },
        ];

        let suggestions = vec![
            "添加单元测试".to_string(),
            "完善错误处理".to_string(),
            "添加文档注释".to_string(),
        ];

        Json(ApiResponse::success(
            CodeReviewResponse {
                score: 80,
                issues,
                suggestions,
            },
            "Success",
        ))
    }
}
